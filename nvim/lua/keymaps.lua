local function map(mode, key, action, desc) vim.keymap.set(mode, key, action, { desc = desc, silent = true }) end
map('n', '<leader>f', function() require('features').pick().builtin.files() end, 'Find files')
map('n', '<leader>b', function() require('features').pick().builtin.buffers() end, 'Switch buffers')
map('n', '<leader>/', function() require('features').pick().builtin.grep_live() end, 'Search project')
map('n', '<leader>e', '<cmd>Explore<cr>', 'File explorer')
map('n', '<S-h>', '<cmd>bprevious<cr>', 'Previous buffer')
map('n', '<S-l>', '<cmd>bnext<cr>', 'Next buffer')
map('n', '<leader>x', '<cmd>bdelete<cr>', 'Close buffer')
map('n', '<leader>w', '<cmd>write<cr>', 'Save')
map('n', '<Esc>', function() require('popups').dismiss() end, 'Dismiss popups and clear search')
map('n', 'gd', function() vim.lsp.buf.definition() end, 'Go to definition')
map('n', 'gr', function() require('features').extra().pickers.lsp({ scope = 'references' }) end, 'References')
map('n', 'gi', function() vim.lsp.buf.implementation() end, 'Implementation')
map('n', 'K', function() vim.lsp.buf.hover() end, 'Documentation')
map('n', '<leader>rn', function() vim.lsp.buf.rename() end, 'Rename symbol')
map({ 'n', 'x' }, '<leader>ca', function() vim.lsp.buf.code_action() end, 'Code action')
map('n', '<leader>d', function() require('diagnostics').setup(); vim.diagnostic.open_float() end, 'Line diagnostics')
map('n', '<leader>D', function() require('features').extra().pickers.diagnostic() end, 'Project diagnostics')
map('n', '<leader>lf', function() require('conform').format({ async = true, lsp_format = 'fallback' }) end, 'Format')
map('n', '<leader>tf', function()
  vim.b.disable_autoformat = not vim.b.disable_autoformat
  vim.notify('Format on save: ' .. (vim.b.disable_autoformat and 'off' or 'on'))
end, 'Toggle buffer format on save')
map('n', '<leader>tb', function()
  local enabled = require('gitsigns').toggle_current_line_blame()
  if enabled == nil then enabled = require('gitsigns.config').config.current_line_blame end
  vim.notify('Inline Git blame: ' .. (enabled and 'on' or 'off'))
end, 'Toggle inline Git blame')
map('n', ']h', function() require('gitsigns').nav_hunk('next') end, 'Next Git hunk')
map('n', '[h', function() require('gitsigns').nav_hunk('prev') end, 'Previous Git hunk')
map('n', '<leader>hp', function() require('gitsigns').preview_hunk() end, 'Preview hunk')
map({ 'n', 'x' }, '<leader>hs', ':Gitsigns stage_hunk<cr>', 'Stage hunk')
map({ 'n', 'x' }, '<leader>hr', ':Gitsigns reset_hunk<cr>', 'Reset hunk')
map('t', '<Esc><Esc>', '<C-\\><C-n>', 'Exit terminal mode')

-- Explore relationships on demand; no background index or always-visible sidebar.
map('n', '<leader>ci', function() require('navigation').hierarchy('call_hierarchy', 'callers') end, 'Incoming calls (callers)')
map('n', '<leader>co', function() require('navigation').hierarchy('call_hierarchy', 'callees') end, 'Outgoing calls (callees)')
map('n', '<leader>ct', function() require('navigation').hierarchy('type_hierarchy', 'supertypes') end, 'Type hierarchy (parents)')
map('n', '<leader>cT', function() require('navigation').hierarchy('type_hierarchy', 'subtypes') end, 'Type hierarchy (children)')
map('n', '<leader>cl', '<cmd>MeowYarn last<cr>', 'Reopen last hierarchy')
map('n', '<leader>s', function() require('features').extra().pickers.lsp({ scope = 'document_symbol' }) end, 'Symbols in current file')
map('n', '<leader>S', function() require('features').extra().pickers.lsp({ scope = 'workspace_symbol_live' }) end, 'Search symbols across project')
map('n', '<leader>A', function() require('features').ast_grep() end, 'Structural AST search (ast-grep)')
map('n', '<leader>j', '<C-o>', 'Go back in navigation history')
map('n', '<leader>k', '<C-i>', 'Go forward in navigation history')
map('n', '<leader>?', function() require('features').extra().pickers.keymaps({ mode = 'n' }) end, 'Search normal-mode shortcuts')
map('n', '<leader>H', function() require('features').extra().pickers.keymaps({ mode = 'all' }) end, 'Search shortcuts in all modes')
map('n', '<leader>m', function() require('shortcuts').show_daily() end, 'Most-used daily keys cheatsheet')
map('n', '<leader>gs', function() require('git_changes').status() end, 'Git status: browse all changed files')
map('n', '<leader>gS', function() require('git_changes').review_commits() end, 'Git review: committed branch/agent changes')
map('n', '<leader>gy', function() require('git_changes').yank_reference(false) end, 'Copy file:line reference for AI prompt')
map('x', '<leader>gy', function() require('git_changes').yank_reference(true) end, 'Copy file:start-end reference for AI prompt')
map('n', '<leader>gd', function() require('features').extra().pickers.git_hunks() end, 'Git diff: unstaged hunks')
map('n', '<leader>gD', function() require('features').extra().pickers.git_hunks({ scope = 'staged' }) end, 'Git diff: staged hunks')
map('n', '<leader>gb', function() require('gitsigns').blame_line({ full = true }) end, 'Git blame: current line commit')
